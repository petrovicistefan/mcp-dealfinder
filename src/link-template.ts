import { buildTrackedUrl } from "./links.js";

export interface DerivedTemplate {
  ok: boolean;
  template?: string;
  /** Account-level values pulled out of the sample link (IDs); they go in `networks.<name>.params`. */
  params: Record<string, string>;
  /**
   * exact: rebuilding the sample from the product URL gives the same link.
   * equivalent: same link once query values are decoded (e.g. the network left the destination unencoded).
   */
  roundTrip?: "exact" | "equivalent" | "mismatch";
  notes: string[];
}

/** Query keys that carry a per-click label chosen by the publisher. */
const SUBID_KEY = /^(sub[_-]?id|sub[_-]?ref|clickref\d*|custom[_-]?id|ascsubtag)$/i;
const RESERVED = new Set(["url", "urlEncoded", "subId"]);

const fail = (note: string): DerivedTemplate => ({ ok: false, params: {}, notes: [note] });

function httpUrl(s: string): URL | undefined {
  try {
    const u = new URL(s);
    return u.protocol === "https:" || u.protocol === "http:" ? u : undefined;
  } catch {
    return undefined;
  }
}

/** Finds the product URL inside the link, encoded or raw, as given or normalised (`https://x.com` → `https://x.com/`). */
function locate(link: string, product: string): { start: number; length: number; raw: boolean } | undefined {
  const lower = link.toLowerCase();
  for (const candidate of new Set([product, new URL(product).toString()])) {
    for (const [text, raw] of [
      [encodeURIComponent(candidate), false],
      [candidate, true],
    ] as const) {
      const i = lower.indexOf(text.toLowerCase());
      if (i >= 0) return { start: i, length: text.length, raw };
    }
  }
  return undefined;
}

function sameLink(a: string, b: string, ignoreKeys: Set<string>): boolean {
  const ua = new URL(a);
  const ub = new URL(b);
  if (ua.origin !== ub.origin || ua.pathname !== ub.pathname) return false;
  const entries = (u: URL) =>
    [...u.searchParams.entries()]
      .filter(([k]) => !ignoreKeys.has(k))
      .map(([k, v]) => `${k}=${v}`)
      .sort();
  return JSON.stringify(entries(ua)) === JSON.stringify(entries(ub));
}

/**
 * Turns ONE link generated by an affiliate network into a `template` network config.
 * `productUrl` must be the exact URL that was pasted into the network's link generator.
 * Nothing is guessed about the network: the template is the sample itself with the
 * destination replaced by `{urlEncoded}`, and the result is verified by rebuilding the sample.
 */
export function deriveTemplate(sampleLink: string, productUrl: string): DerivedTemplate {
  const link = sampleLink.trim();
  const product = productUrl.trim();
  const sample = httpUrl(link);
  if (!sample) return fail("The sample link must be a full http(s) URL.");
  if (!httpUrl(product)) return fail("The product URL must be a full http(s) URL.");

  const hit = locate(link, product);
  if (!hit) {
    return fail(
      "Could not find the product URL inside the sample link. Generate the link for a real product page and pass that exact URL.",
    );
  }

  const notes: string[] = [];
  if (hit.raw) {
    notes.push(
      "The network left the destination unencoded in your sample. The template encodes it, which is safer for URLs containing ? or &. Click one generated link once to confirm it lands on the product page.",
    );
  }
  if (/(^|\.)awin1\.com$/.test(sample.hostname)) {
    notes.push('Awin has a built-in kind: use { "kind": "awin", "affiliateId": "<awinaffid>" } and set "merchantId" on each feed instead.');
  }
  if (/(^|\.)amazon\.[a-z]{2,3}(\.[a-z]{2})?$/.test(sample.hostname)) {
    notes.push('Amazon has a built-in kind: use { "kind": "amazon", "tag": "<your tag>" }.');
  }
  if (/\/\d{5,}(\/|$)/.test(sample.pathname)) {
    notes.push("An ID appears inside the link path. It stays literal in the template, which is fine for your own account.");
  }

  let template = link.slice(0, hit.start) + "{urlEncoded}" + link.slice(hit.start + hit.length);
  const params: Record<string, string> = {};
  const subKeys = new Set<string>();

  const q = template.indexOf("?");
  if (q >= 0) {
    const hash = template.indexOf("#", q);
    const end = hash >= 0 ? hash : template.length;
    const pairs = template
      .slice(q + 1, end)
      .split("&")
      .map((pair) => {
        const eq = pair.indexOf("=");
        if (eq < 0) return pair;
        const key = pair.slice(0, eq);
        const value = pair.slice(eq + 1);
        if (value.includes("{urlEncoded}") || RESERVED.has(key)) return pair;
        if (SUBID_KEY.test(key)) {
          subKeys.add(key);
          return `${key}={subId}`;
        }
        // IDs look like 4+ chars of [\w.-] with at least one digit; words like "quicklink" stay literal.
        if (/^\w+$/.test(key) && /^[\w.-]+$/.test(value) && value.length >= 4 && /\d/.test(value)) {
          params[key] = value;
          return `${key}={${key}}`;
        }
        return pair;
      });
    template = template.slice(0, q + 1) + pairs.join("&") + template.slice(end);
  }
  if (subKeys.size > 0) {
    notes.push(`Tracking label parameter(s) ${[...subKeys].join(", ")} now take the sub_id given to the tools.`);
  }
  if (Object.keys(params).length > 0) {
    notes.push(
      `Extracted ${Object.keys(params).join(", ")}. If one of them differs per advertiser/program, move it from "networks" to that feed's "params".`,
    );
  }

  const rebuilt = buildTrackedUrl(product, { kind: "template", template, params });
  let roundTrip: DerivedTemplate["roundTrip"] = "mismatch";
  if (rebuilt.tracked) {
    if (rebuilt.url === link) roundTrip = "exact";
    else if (sameLink(rebuilt.url, link, subKeys)) roundTrip = "equivalent";
  } else {
    notes.push(`Rebuilding failed: ${rebuilt.reason}`);
  }
  if (roundTrip === "mismatch") notes.push("The rebuilt link does not match your sample; do not use this template as is.");

  return { ok: roundTrip !== "mismatch", template, params, roundTrip, notes };
}
